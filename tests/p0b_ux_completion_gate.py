def short_route_cannot_bypass(page):
 start_workstation(page)
 inspect_wo(page,"service")
 go_hub_from_station(page)
 save_theory_on_service(page)
 case=page.get_by_test_id("hub-case-board")
 check(page.get_by_test_id("hub-open-c17").count()==0,"Hub still manufactures C-17")
 check(page.get_by_test_id("hub-end-session").count()==0,"Session can end without real interruption")
 check(page.get_by_test_id("hub-investigate-before-alert").is_visible(),"No wayfinding after early theory")
 guidance_fits_board(page,"hub-investigate-before-alert")
 check("STANDBY" in case.inner_text(),"C-17 wrongly shown active")
 check("NOT SAVED" in case.inner_text(),"Comparison wrongly shown active")
 snap(page,"early-theory-no-alert")
 page.clock.fast_forward(60000)
 check(page.get_by_test_id("incoming-interruption").count()==0,"Alert fires in inactive Hub")
 check(page.get_by_test_id("hub-open-c17").count()==0,"Alert button appears without trigger")
 hub_to_workstation(page)
 page.get_by_test_id("workstation-focus").wait_for()
 inspect_wo(page,"parts")
 page.get_by_test_id("workstation-focus-select").select_option("trace-part")
 page.clock.fast_forward(30000)
 check(page.get_by_test_id("incoming-interruption").count()==0,"Waiting after selecting a focus must not trigger C-17")
 prepare_workstation_check(page)
 page.clock.fast_forward(1100)
 page.get_by_test_id("incoming-interruption").wait_for()
 check(page.get_by_test_id("workstation-focus").count()==1,"Alert not triggered during Workstation investigation")
 snap(page,"genuine-workstation-alert")
 page.get_by_test_id("minimize-incident").click()
 go_hub_from_station(page)
 check(page.get_by_test_id("hub-open-c17").is_visible(),"Pending alert cannot be reopened from Hub")
 page.get_by_test_id("hub-open-c17").click()
 page.get_by_test_id("incoming-interruption").wait_for()
 handle_and_go_hub(page)
 check(page.get_by_test_id("hub-end-session").count()==0,"Session can end before recovery activity")
 check(page.get_by_test_id("hub-resume-before-finish").is_visible(),"No guidance to re-engage")
 guidance_fits_board(page,"hub-resume-before-finish")
 snap(page,"handled-but-not-resumed")
 hub_to_maintenance(page)
 page.get_by_test_id("maintenance-hub-exit").click()
 page.get_by_test_id("hub-scene").wait_for()
 check(page.get_by_test_id("hub-end-session").count()==0,"Walking to Maintenance counted as task recovery")
 hub_to_workstation(page)
 page.get_by_test_id("back-to-maintenance").click()
 page.get_by_test_id("maintenance-hub-exit").click()
 page.get_by_test_id("hub-scene").wait_for()
 check(page.get_by_test_id("hub-end-session").count()==0,"Opening Workstation without action counted as recovery")
 hub_to_workstation(page)
 inspect_wo(page,"parts")
 go_hub_from_station(page)
 check(page.get_by_test_id("hub-end-session").is_visible(),"Actual reinspection did not unlock ending")
 page.get_by_test_id("hub-end-session").click()
 page.get_by_test_id("reflection-scene").wait_for()
 review=page.get_by_test_id("reflection-scene").inner_text()
 check("First thread resumed: Coupler replacement" in review,"Recovery was not recorded as actual task")
 check("Interruptions encountered: 1" in review,"C-17 not counted")
 snap(page,"valid-completed-recovery")
