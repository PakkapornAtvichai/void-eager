"""UX-01 and UX-02: serious-game completion must require real interruption
and meaningful re-engagement; the Workstation focus selector must not hide in
the scrollable report. Run with Vite at localhost:5173 and Playwright Chrome.
"""
import os, tempfile, traceback
from pathlib import Path
from playwright.sync_api import sync_playwright
from physical_nav import hub_to_maintenance, hub_to_storage, storage_to_hub, hub_to_workstation
from active_work import prepare_workstation_check, second_storage_inspection

BASE="http://127.0.0.1:5173/"
OUT=Path(os.environ.get("VOID_EAGER_TEST_OUT",tempfile.gettempdir()))
OUT.mkdir(parents=True,exist_ok=True)
passed=[]
errors=[]
def check(cond,msg):
 if not cond:raise AssertionError(msg)
def snap(page,name):
 page.screenshot(path=str(OUT/("UXFIX-"+name+".png")))
def guidance_fits_board(page,test_id):
 hint=page.get_by_test_id(test_id)
 box=hint.bounding_box()
 board=page.get_by_test_id("hub-case-board").bounding_box()
 check(box is not None and board is not None,"Hub guidance missing")
 check(box["y"]>=board["y"] and box["y"]+box["height"] <= board["y"]+board["height"]-2,
       "Hub next-action guidance is clipped outside its monitor")
def new_game(browser,w=1464,h=815):
 page=browser.new_page(viewport={"width":w,"height":h},device_scale_factor=1)
 page.clock.install()
 page.set_default_timeout(9500)
 errs=[]
 page.on("pageerror",lambda e:errs.append(str(e)))
 return page,errs
def run(browser,name,test,w=1464,h=815):
 page,errs=new_game(browser,w,h)
 try:
  test(page)
  check(not errs,"Unexpected JS exceptions: "+str(errs))
  passed.append(name)
  print("PASS",name,flush=True)
 except Exception as e:
  errors.append(name+": "+str(e)[:650])
  print("FAIL",name,type(e).__name__,str(e)[:650],flush=True)
  print(traceback.format_exc()[-1350:],flush=True)
  snap(page,"FAIL-"+name)
 finally:
  page.close()
