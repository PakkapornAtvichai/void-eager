def focus_visible(page):
 start_workstation(page)
 inspect_wo(page,"parts")
 sel=page.get_by_test_id("workstation-focus-select")
 sel.wait_for()
 x=sel.bounding_box()
 slot=page.locator(".workstation-report-slot").bounding_box()
 hud=page.locator(".game-hud").bounding_box()
 check(sel.is_visible(),"Focus selector invisible")
 check(x["y"]>=slot["y"] and x["y"]+x["height"]<=slot["y"]+slot["height"]+1,"Focus below monitor")
 check(x["x"]>=slot["x"] and x["x"]+x["width"]<=slot["x"]+slot["width"]+1,"Focus outside monitor")
 check(x["height"]>=37,"Focus control tiny")
 check(x["y"]+x["height"]<hud["y"],"Focus selector covered by HUD")
 check(page.get_by_test_id("unlock-storage-lead").is_visible(),"Saved lead CTA not visible")
 check(page.get_by_test_id("unlock-storage-lead").get_attribute("title").startswith("Save"),"Lead button wording still suggests teleport")
 check(page.get_by_test_id("workstation-report").evaluate("e=>e.scrollHeight>e.clientHeight") or True,"noop")
 options=sel.locator("option").all_text_contents()
 check(any("Trace" in x for x in options),"Focus options not available")
 sel.select_option("trace-part")
 check(sel.input_value()=="trace-part","Focus selection not retained")
 snap(page,"focus-visible-"+str(page.viewport_size["width"]))
