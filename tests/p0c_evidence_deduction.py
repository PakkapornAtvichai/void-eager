import os, tempfile, traceback
from pathlib import Path
from playwright.sync_api import sync_playwright

BASE="http://127.0.0.1:5173/"
OUT=Path(os.environ.get("VOID_EAGER_TEST_OUT", tempfile.gettempdir()))
OUT.mkdir(parents=True,exist_ok=True)
successful=[]
issues=[]

def require(test,message):
    if not test: raise AssertionError(message)
def shot(page,name):
    page.screenshot(path=str(OUT/("VOID-EAGER-P0C-"+name+".png")))
def open_workstation(page):
    page.goto(BASE)
    page.get_by_test_id("begin-coupler-investigation").click()
    page.get_by_test_id("inspect-work-order").click()
def inspect_field(page,field):
    page.get_by_test_id("inspect-wo-"+field).click()
    page.get_by_test_id("workorder-field-dialog").wait_for()
    page.get_by_test_id("close-evidence").click()
def go_hub_from_workstation(page):
    page.get_by_test_id("back-to-maintenance").click()
    page.get_by_test_id("maintenance-hub-exit").click()
    page.get_by_test_id("hub-scene").wait_for()
def open_storage_from_hub(page):
    page.get_by_test_id("hub-visit-storage").click()
    page.get_by_test_id("storage-scene").wait_for()
def open_crate(page):
    page.get_by_test_id("storage-open-crate").click()
    page.get_by_test_id("close-evidence").click()
def inspect_condition(page):
    page.get_by_test_id("inspect-storage-coupler").click()
    page.get_by_test_id("storage-detail-dialog").wait_for()
    page.get_by_test_id("close-evidence").click()
def inspect_serial(page):
    sel="check-storage-serial" if page.get_by_test_id("check-storage-serial").count() else "storage-review-serial"
    page.get_by_test_id(sel).click()
    page.get_by_test_id("storage-detail-dialog").wait_for()
    page.get_by_test_id("close-evidence").click()
def to_case_review(page):
    page.get_by_test_id("hub-open-case-review").click()
    page.get_by_test_id("deduction-scene").wait_for()
def to_hub_from_case(page):
    page.get_by_test_id("case-review-back-hub").click()
    page.get_by_test_id("hub-scene").wait_for()
def run(name,cb,size=(1464,815)):
    with sync_playwright() as p:
        browser=p.chromium.launch(channel="chrome",headless=True)
        page=browser.new_page(viewport=dict(zip(["width","height"],size)),device_scale_factor=1)
        page.clock.install()
        page.set_default_timeout(9500)
        errs=[]
        page.on("pageerror",lambda e:errs.append(str(e)))
        try:
            cb(page)
            require(not errs,"JS page errors: "+str(errs))
            successful.append(name)
            print("PASS",name,flush=True)
        except Exception as ex:
            issues.append(name+": "+str(ex)[:800])
            print("FAIL",name,type(ex).__name__,str(ex)[:800],flush=True)
            print(traceback.format_exc()[-1200:],flush=True)
            shot(page,"FAIL-"+name)
        finally:
            page.close();browser.close()

def accessible_observation_only(page):
    open_workstation(page)
    require("00" in page.locator(".hud-evidence").inner_text(),"Work Order access should not count evidence")
    go_hub_from_workstation(page)
    require(page.get_by_test_id("hub-open-case-review").count()==0,"Case Review unlocked before observed source")
    page.get_by_test_id("open-coupler-thread").click()
    inspect_field(page,"service")
    require("01" in page.locator(".hud-evidence").inner_text(),"Service inspection did not record evidence")
    go_hub_from_workstation(page)
    require(page.get_by_test_id("hub-open-case-review").is_visible(),"Actual source should unlock Case Review")
    to_case_review(page)
    texts=page.get_by_test_id("case-evidence-picker").inner_text()
    require("routine maintenance logged" in texts,"Service evidence missing")
    require("COUPLER REPLACED" not in texts,"Completion leaked before inspection")
    require("UNUSED" not in texts,"Storage condition leaked")
    require("GSC-8842-A" not in texts,"Serial leaked")
    require(page.get_by_test_id("case-evidence-picker").locator("input").count()==1,"Unobserved evidence selectable")
    page.get_by_label("The recorded replacement happened.").check()
    page.get_by_test_id("save-theory").click()
    require("Choose at least one" in page.get_by_test_id("deduction-scene").inner_text(),"No-citation validation missing")
    page.get_by_text("WO-4471 service field: routine maintenance logged twelve days before the cascade.").click()
    page.get_by_test_id("save-theory").click()
    require("Working theory saved" in page.get_by_test_id("theory-saved").inner_text(),"Theory not saved")
    to_hub_from_case(page)
    require(page.get_by_test_id("hub-open-case-review").inner_text()=="REVISE THEORY","Theory cannot be revisited")
    require(page.get_by_test_id("hub-end-session").count()==0,"End Session prematurely available")
    shot(page,"first-observation-reviewable")

