def expect(value,message):
 if not value: raise AssertionError(message)
def photo(p,name):
 p.screenshot(path=str(OUT/("PH35-"+name+".png")))
def choose_workstation_plan(p,intention="trace-part",plan="trace-issued-unit"):
 p.get_by_test_id("workstation-focus-select").select_option(intention)
 p.get_by_test_id("workstation-prepare-check").click()
 dlg=p.get_by_test_id("verification-worksheet")
 dlg.wait_for()
 expect(p.get_by_test_id("incoming-interruption").count()==0,"Alert opened while plan dialog visible")
 label={"trace-issued-unit":"Trace the issued unit to Storage B-04",
        "check-installation":"Look for installation verification",
        "review-completion":"Re-read the recorded completion"}[plan]
 p.get_by_test_id("verification-next-choices").get_by_label(label).check()
 p.get_by_test_id("continue-verification").click()
 p.get_by_test_id("unfinished-verification-check").wait_for()
def new_game(p,w,h):
 browser=p.chromium.launch(channel="chrome",headless=True)
 pg=browser.new_page(viewport={"width":w,"height":h},device_scale_factor=1)
 pg.clock.install()
 pg.set_default_timeout(9000)
 errs=[]
 pg.on("pageerror",lambda e: errs.append(str(e)))
 return browser,pg,errs
def run(name,fn,w=1464,h=815):
 with sync_playwright() as p:
  browser,pg,errs=new_game(p,w,h)
  try:
   fn(pg)
   expect(not errs,"JavaScript errors "+str(errs))
   passed.append(name)
   print("PASS",name,flush=True)
  except Exception as e:
   failed.append(name+": "+str(e)[:500])
   print("FAIL",name,type(e).__name__,str(e)[:500],flush=True)
   print(traceback.format_exc()[-1400:],flush=True)
   photo(pg,"FAIL-"+name)
  finally:
   pg.close();browser.close()
