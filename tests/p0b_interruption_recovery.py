def run(name,func,w=1464,h=815):
 with sync_playwright() as p:
  browser=p.chromium.launch(channel="chrome",headless=True)
  page=browser.new_page(viewport={"width":w,"height":h},device_scale_factor=1)
  page.clock.install()
  page.set_default_timeout(9500)
  errs=[]
  page.on("pageerror",lambda error:errs.append(str(error)))
  try:
   func(page)
   check(not errs,"JavaScript errors "+str(errs))
   passed.append(name)
   print("PASS",name,flush=True)
  except Exception as ex:
   issues.append(name+": "+str(ex)[:850])
   print("FAIL",name,type(ex).__name__,str(ex)[:850],flush=True)
   print(traceback.format_exc()[-1400:],flush=True)
   shot(page,"FAIL-"+name)
  finally:browser.close()
